# Run the public lex1dx options on bundled athletics data and a synthetic sample.
# Athletics times have two decimal places, so they are used for the basic API,
# weights, and order independence. Significant-digit grouping is shown on a
# fixed-seed lognormal sample generated in this script.
# Redirect stdout to docs/examples_output_r.md.

report <- function(title, r, exact = NULL) {
  cat("### ", title, "\n\n", sep = "")
  cat("bounds: ", paste(as.integer(r$bounds), collapse = ", "), "\n", sep = "")
  cat("sizes: ", paste(as.integer(r$sizes), collapse = ", "), "\n", sep = "")
  cat("centers: ", paste(sprintf("%.6f", r$centers), collapse = ", "), "\n", sep = "")
  cat("upper: ", paste(sprintf("%.4f", r$upper), collapse = ", "), "\n", sep = "")
  cat(sprintf("sse: %.12g\n", r$sse))
  cat(sprintf("D=%s Dprime=%s sig=%s sweeps=%s moves=%s presorted=%s k=%s\n",
              r$D, r$Dprime, r$sig, r$sweeps, r$moves,
              as.logical(r$presorted), length(r$sizes)))
  if (!is.null(exact)) {
    same <- identical(as.integer(r$bounds), as.integer(exact$bounds))
    cat(sprintf("exact sse: %.12g\n", exact$sse))
    cat("exact bounds: ", paste(as.integer(exact$bounds), collapse = ", "), "\n", sep = "")
    if (exact$sse < 1e-12) {
      cat(sprintf("REE vs exact: not reported (exact SSE is near 0); excess SSE = %.12g\n", r$sse - exact$sse))
    } else {
      pct <- (r$sse - exact$sse) / exact$sse * 100
      ree_s <- if (abs(pct) < 1e-12) "0" else sprintf("%.6g%%", pct)
      cat("REE vs exact: ", ree_s, "\n", sep = "")
    }
    cat("bounds match exact: ", same, "\n", sep = "")
  }
  cat("\n")
}

cat("# lex1dx example outputs (R)\n\n")
cat("Generated by inst/examples/cluster_athletics.R from lex1dx 0.1.1.\n\n")
cat("Source: World Athletics 100m all-time lists, retrieved January 2024.\n")
cat("The files are sample inputs for testing and demonstrating the algorithms.\n")
cat("Only the time column is used. Athlete names are not included.\n\n")

library(lex1dx)

cat("## Datasets and default_M\n\n")
cat("names: ", paste(load_dataset(), collapse = ", "), "\n", sep = "")
x20 <- load_dataset("athletics20")
x2379 <- load_dataset("worldathletics-mens-100m-2379")
cat(sprintf("athletics20: n=%d, %d distinct times, %.2f to %.2f.\n",
            length(x20), length(unique(x20)), x20[1], x20[length(x20)]))
cat(sprintf("worldathletics-mens-100m-2379: n=%d, %d distinct times, %.2f to %.2f.\n",
            length(x2379), length(unique(x2379)), x2379[1], x2379[length(x2379)]))
cat("athletics20 is the first 20 rows of the 2,379-row list.\n")
cat(sprintf("default_M(4) = %d\n", default_M(4L)))
cat(sprintf("default_M(64) = %d\n", default_M(64L)))
cat(sprintf("default_M(256) = %d\n\n", default_M(256L)))

cat("## athletics20\n\n")
cat("The file is already sorted. Default M is 4096, which is larger than the 12 distinct times, so Collapse does not reduce the atoms.\n")
cat("These times have two decimal places, so significant-digit grouping is not demonstrated here.\n\n")

for (k in c(2L, 4L, 8L)) {
  r <- cluster(x20, k)
  ex <- cluster(x20, k, mode = "exact", solver = "ckmeans")
  report(sprintf("athletics20, k=%d, mode=tuned, M=default", k), r, ex)
}

r_m <- cluster(x20, 4L, M = default_M(4L))
report("athletics20, k=4, mode=tuned, M=default_M(4) explicit", r_m,
       cluster(x20, 4L, mode = "exact", solver = "ckmeans"))

for (solver in c("wilber", "ckmeans")) {
  r <- cluster(x20, 4L, mode = "exact", solver = solver)
  report(sprintf("athletics20, k=4, mode=exact, solver=%s", solver), r,
         cluster(x20, 4L, mode = "exact", solver = "ckmeans"))
}

r_clamp <- cluster(x20, 20L)
cat("### athletics20, k=20 (clamped to the number of distinct times)\n\n")
cat(sprintf("requested k=20, result k=%d, D=%s, sse=%.12g\n\n", length(r_clamp$sizes), r_clamp$D, r_clamp$sse))

r_def <- cluster(x20, 4L)
cat("### order independence\n\n")
set.seed(0)
shuffled <- sample(x20)
r_shuf <- cluster(shuffled, 4L)
same <- identical(as.integer(r_def$bounds), as.integer(r_shuf$bounds)) &&
  isTRUE(all.equal(r_def$sse, r_shuf$sse))
cat(sprintf("The input is pre-sorted (presorted=%s).\n", as.logical(r_def$presorted)))
cat(sprintf("A shuffled copy gives the same bounds and SSE (presorted=%s): %s.\n\n",
            as.logical(r_shuf$presorted), same))

cat("## Weights\n\n")
cat("Equal times in the input already act as integer counts.\n")
tab <- table(x20)
vals <- as.numeric(names(tab))
wts <- as.numeric(tab)
cat("athletics20 unique times: ", paste(sprintf("%.2f", vals), collapse = ", "), "\n", sep = "")
cat("counts: ", paste(as.integer(wts), collapse = ", "), "\n", sep = "")
r_w <- cluster(vals, 4L, weights = wts)
mass <- mapply(function(lo, hi) sum(wts[(lo + 1L):hi]), r_w$bounds[-length(r_w$bounds)], r_w$bounds[-1])
match <- isTRUE(all.equal(r_def$sse, r_w$sse)) &&
  isTRUE(all.equal(as.numeric(mass), as.numeric(r_def$sizes)))
cat("Clustering the 12 distinct times with those integer counts as weights matches clustering the expanded 20 values.\n")
cat(sprintf("Same SSE and per-bin weight mass at k=4: %s.\n\n", match))

r_uni <- cluster(vals, 4L)
cat("A different weighting changes the partition.\n")
cat("Clustering the 12 distinct times with no weights gives each time a weight of 1.\n\n")
report("athletics20 distinct times only, k=4, unweighted", r_uni,
       cluster(vals, 4L, mode = "exact", solver = "ckmeans"))

w_nonuni <- rep(1, length(x20))
w_nonuni[1] <- 10
r_nw <- cluster(x20, 4L, weights = w_nonuni)
cat("A non-uniform weight is passed directly. Here 9.58 has weight 10 and every other athletics20 row has weight 1.\n\n")
report("athletics20, k=4, weight 10 on 9.58", r_nw)

cat("## worldathletics-mens-100m-2379\n\n")
cat("This list has 58 distinct times. Default M is still 4096, so the default tuned run does not collapse.\n")
cat("An explicit M smaller than 58 is included so Collapse actually reduces the atoms.\n\n")
for (k in c(2L, 4L, 8L)) {
  r <- cluster(x2379, k)
  ex <- cluster(x2379, k, mode = "exact", solver = "ckmeans")
  report(sprintf("2379-row list, k=%d, mode=tuned, M=default", k), r, ex)
}
for (M in c(8L, 16L, 32L)) {
  r <- cluster(x2379, 8L, M = M)
  report(sprintf("2379-row list, k=8, mode=tuned, M=%d", M), r,
         cluster(x2379, 8L, mode = "exact", solver = "ckmeans"))
}

cat("## Significant-digit grouping on a synthetic sample\n\n")
cat("N=10000 draws from a lognormal, generated with set.seed(1); x <- rlnorm(10000).\n")
cat("This is full double precision, so grouping at sig=1..9 can be seen.\n")
cat("mode='sig5' is an alias for sig=5.\n")
cat("If grouping at that sig yields fewer than k groups, precision is raised (up to 15, then raw atoms) so k is kept when the raw data has at least k distinct values.\n")
cat("Result.sig is the sig actually used (0 if the fallback reached raw atoms). Dprime is the number of groups after that grouping.\n\n")
set.seed(1)
syn <- rlnorm(10000)
k <- 8L
ex <- cluster(syn, k, mode = "exact", solver = "ckmeans")
cat(sprintf("synthetic n=%d, D=%d, k=%d, exact sse=%.12g\n\n",
            length(syn), length(unique(syn)), k, ex$sse))
cat("sig  Dprime  SSE  REE  time_s\n")
for (d in 0:9) {
  t0 <- proc.time()[["elapsed"]]
  r <- cluster(syn, k, sig = d)
  dt <- proc.time()[["elapsed"]] - t0
  pct <- if (ex$sse == 0) 0 else (r$sse - ex$sse) / ex$sse * 100
  ree_s <- if (abs(pct) < 1e-12) "0" else sprintf("%.6g%%", pct)
  cat(sprintf("%3d  %6d  %.12g  %s  %.4f\n", d, as.integer(r$Dprime), r$sse, ree_s, dt))
}
cat("\n")
r_alias <- cluster(syn, k, mode = "sig5")
r5 <- cluster(syn, k, sig = 5L)
cat(sprintf("mode='sig5' matches sig=5: sig=%s, same SSE: %s.\n\n",
            r_alias$sig, isTRUE(all.equal(r_alias$sse, r5$sse))))

cat("### k-preserving fallback\n\n")
cat("Four tight groups around 0, 1.000012, 1.000017, and 2.\n")
cat("At sig=5 the middle pair share a key, so a 5-digit grouping would have only 3 groups.\n")
cat("The fallback raises precision to 6, Dprime becomes 4, and k=4 is kept. Result.sig reports 6.\n\n")
tight <- c(rep(0, 50), 1.000012 + 1e-10 * (0:49 - 25), 1.000017 + 1e-10 * (0:49 - 25), rep(2, 50))
for (d in c(5L, 6L)) {
  r <- cluster(tight, 4L, sig = d)
  report(sprintf("tight groups, requested k=4, sig=%d", d), r,
         cluster(tight, 4L, mode = "exact", solver = "ckmeans"))
}
