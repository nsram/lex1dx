#!/usr/bin/env python3
"""Run the public lex1dx options on bundled athletics data and a synthetic sample.

Athletics times have two decimal places, so they are used for the basic API,
weights, and order independence. Significant-digit grouping is shown on a
fixed-seed lognormal sample generated in this script, not a bundled file.

REE is relative excess SSE versus cluster(..., mode='exact', solver='ckmeans').
Redirect stdout to docs/examples_output.md.
"""
from __future__ import annotations

import time

import numpy as np

import lex1dx


def exact_1d(x, k):
    """Reference partition from the public exact ckmeans solver."""
    r = lex1dx.cluster(x, k, mode="exact", solver="ckmeans")
    return {"bounds": list(map(int, r.bounds)), "sizes": list(map(int, r.sizes)), "sse": float(r.sse)}


def ree(sse, exact_sse):
    if exact_sse == 0:
        return 0.0 if sse == 0 else float("inf")
    return (sse - exact_sse) / exact_sse * 100.0


def fmt_vec(a, digits=4):
    return ", ".join(f"{v:.{digits}f}" if isinstance(v, float) else str(int(v)) for v in a)


def fmt_ree(pct):
    if pct == 0 or abs(pct) < 1e-12:
        return "0"
    return f"{pct:.6g}%"


def report(title, r, exact=None):
    print(f"### {title}")
    print()
    print(f"bounds: {fmt_vec(r.bounds, 0)}")
    print(f"sizes: {fmt_vec(r.sizes, 0)}")
    print(f"centers: {fmt_vec(r.centers, 6)}")
    print(f"upper: {fmt_vec(r.upper, 4)}")
    print(f"sse: {r.sse:.12g}")
    print(
        f"D={r.D} Dprime={r.Dprime} sig={r.sig} "
        f"sweeps={r.sweeps} moves={r.moves} "
        f"presorted={bool(r.presorted)} k={r.k}"
    )
    if exact is not None:
        same_bounds = list(r.bounds) == list(exact["bounds"])
        print(f"exact sse: {exact['sse']:.12g}")
        print(f"exact bounds: {fmt_vec(exact['bounds'], 0)}")
        if exact["sse"] < 1e-12:
            print(f"REE vs exact: not reported (exact SSE is near 0); excess SSE = {r.sse - exact['sse']:.12g}")
        else:
            print(f"REE vs exact: {fmt_ree(ree(r.sse, exact['sse']))}")
        print(f"bounds match exact: {same_bounds}")
    print()


def main():
    print("# lex1dx example outputs")
    print()
    print("Generated by `examples/cluster_athletics.py` from lex1dx 0.1.1.")
    print()
    print("Source: World Athletics 100m all-time lists, retrieved January 2024.")
    print("The files are sample inputs for testing and demonstrating the algorithms.")
    print("Only the time column is used. Athlete names are not included.")
    print()

    print("## Datasets and default_M")
    print()
    print("names:", ", ".join(lex1dx.datasets.names()))
    x20 = lex1dx.datasets.load("athletics20")
    x2379 = lex1dx.datasets.load("worldathletics-mens-100m-2379")
    print(f"athletics20: n={len(x20)}, {len(np.unique(x20))} distinct times, {x20[0]:.2f} to {x20[-1]:.2f}.")
    print(f"worldathletics-mens-100m-2379: n={len(x2379)}, {len(np.unique(x2379))} distinct times, {x2379[0]:.2f} to {x2379[-1]:.2f}.")
    print("athletics20 is the first 20 rows of the 2,379-row list.")
    print(f"default_M(4) = {lex1dx.default_M(4)}")
    print(f"default_M(64) = {lex1dx.default_M(64)}")
    print(f"default_M(256) = {lex1dx.default_M(256)}")
    print()

    print("## athletics20")
    print()
    print("The file is already sorted. Default M is 4096, which is larger than the 12 distinct times, so Collapse does not reduce the atoms.")
    print("These times have two decimal places, so significant-digit grouping is not demonstrated here.")
    print()
    for k in (2, 4, 8):
        r = lex1dx.cluster(x20, k)
        report(f"athletics20, k={k}, mode=tuned, M=default", r, exact_1d(x20, k))

    r_m = lex1dx.cluster(x20, 4, M=lex1dx.default_M(4))
    report("athletics20, k=4, mode=tuned, M=default_M(4) explicit", r_m, exact_1d(x20, 4))

    for solver in ("wilber", "ckmeans"):
        r = lex1dx.cluster(x20, 4, mode="exact", solver=solver)
        report(f"athletics20, k=4, mode=exact, solver={solver}", r, exact_1d(x20, 4))

    r_clamp = lex1dx.cluster(x20, 20)
    print("### athletics20, k=20 (clamped to the number of distinct times)")
    print()
    print(f"requested k=20, result k={r_clamp.k}, D={r_clamp.D}, sse={r_clamp.sse:.12g}")
    print()

    r_def = lex1dx.cluster(x20, 4)
    labels = r_def.assign([9.58, 9.76, 9.84, 10.0])
    print("### assign")
    print()
    print(f"assign([9.58, 9.76, 9.84, 10.0]) on the k=4 tuned fit: {list(map(int, labels))}")
    print()

    print("### order independence")
    print()
    rng = np.random.default_rng(0)
    shuffled = rng.permutation(x20)
    r_shuf = lex1dx.cluster(shuffled, 4)
    same = list(r_def.bounds) == list(r_shuf.bounds) and r_def.sse == r_shuf.sse
    print(f"The input is pre-sorted (presorted={bool(r_def.presorted)}).")
    print(f"A shuffled copy gives the same bounds and SSE (presorted={bool(r_shuf.presorted)}): {same}.")
    print()

    print("## Weights")
    print()
    print("Equal times in the input already act as integer counts.")
    vals, counts = np.unique(x20, return_counts=True)
    wts = counts.astype(np.float64)
    print("athletics20 unique times: " + ", ".join(f"{v:.2f}" for v in vals))
    print("counts: " + ", ".join(str(int(c)) for c in counts))
    r_w = lex1dx.cluster(vals, 4, weights=wts)
    mass = [float(wts[lo:hi].sum()) for lo, hi in zip(r_w.bounds[:-1], r_w.bounds[1:])]
    match = (
        r_def.sse == r_w.sse
        and np.allclose(r_def.centers, r_w.centers)
        and list(mass) == list(r_def.sizes)
    )
    print("Clustering the 12 distinct times with those integer counts as weights matches clustering the expanded 20 values.")
    print(f"Same centers, SSE, and per-bin weight mass at k=4: {match}.")
    print()
    r_uni = lex1dx.cluster(vals, 4)
    print("A different weighting changes the partition.")
    print("Clustering the 12 distinct times with no weights gives each time a weight of 1.")
    print()
    report("athletics20 distinct times only, k=4, unweighted", r_uni, exact_1d(vals, 4))

    w_nonuni = np.ones(len(x20), dtype=np.float64)
    w_nonuni[0] = 10.0
    r_nw = lex1dx.cluster(x20, 4, weights=w_nonuni)
    print("A non-uniform weight is passed directly. Here 9.58 has weight 10 and every other athletics20 row has weight 1.")
    print()
    report("athletics20, k=4, weight 10 on 9.58", r_nw)

    print("## worldathletics-mens-100m-2379")
    print()
    print("This list has 58 distinct times. Default M is still 4096, so the default tuned run does not collapse.")
    print("An explicit M smaller than 58 is included so Collapse actually reduces the atoms.")
    print()
    for k in (2, 4, 8):
        r = lex1dx.cluster(x2379, k)
        report(f"2379-row list, k={k}, mode=tuned, M=default", r, exact_1d(x2379, k))
        rex = lex1dx.cluster(x2379, k, mode="exact", solver="ckmeans")
        report(f"2379-row list, k={k}, mode=exact, solver=ckmeans", rex, exact_1d(x2379, k))

    for M in (8, 16, 32):
        r = lex1dx.cluster(x2379, 8, M=M)
        report(f"2379-row list, k=8, mode=tuned, M={M}", r, exact_1d(x2379, 8))

    print("## Significant-digit grouping on a synthetic sample")
    print()
    print("N=10000 draws from a lognormal, generated with numpy default_rng(1).")
    print("This is full double precision, so grouping at sig=1..9 can be seen.")
    print("mode='sig5' is an alias for sig=5.")
    print("If grouping at that sig yields fewer than k groups, precision is raised (up to 15, then raw atoms) so k is kept when the raw data has at least k distinct values.")
    print("Result.sig is the sig actually used (0 if the fallback reached raw atoms). Dprime is the number of groups after that grouping.")
    print()
    syn = np.random.default_rng(1).lognormal(size=10_000)
    k = 8
    ex = exact_1d(syn, k)
    print(f"synthetic n={len(syn)}, D={len(np.unique(syn))}, k={k}, exact sse={ex['sse']:.12g}")
    print()
    print("sig  Dprime  SSE  REE  time_s")
    for d in range(0, 10):
        t0 = time.perf_counter()
        r = lex1dx.cluster(syn, k, sig=d)
        dt = time.perf_counter() - t0
        print(f"{d:3d}  {r.Dprime:6d}  {r.sse:.12g}  {fmt_ree(ree(r.sse, ex['sse']))}  {dt:.4f}")
    print()
    r_alias = lex1dx.cluster(syn, k, mode="sig5")
    r5 = lex1dx.cluster(syn, k, sig=5)
    print(f"mode='sig5' matches sig=5: sig={r_alias.sig}, same SSE: {r_alias.sse == r5.sse}.")
    print()

    print("### k-preserving fallback")
    print()
    print("Four tight groups around 0, 1.000012, 1.000017, and 2.")
    print("At sig=5 the middle pair share a key, so a 5-digit grouping would have only 3 groups.")
    print("The fallback raises precision to 6, Dprime becomes 4, and k=4 is kept. Result.sig reports 6.")
    print()
    tight = np.concatenate([
        np.zeros(50),
        1.000012 + 1e-10 * (np.arange(50) - 25),
        1.000017 + 1e-10 * (np.arange(50) - 25),
        np.full(50, 2.0),
    ])
    for d in (5, 6):
        r = lex1dx.cluster(tight, 4, sig=d)
        report(f"tight groups, requested k=4, sig={d}", r, exact_1d(tight, 4))


if __name__ == "__main__":
    main()
